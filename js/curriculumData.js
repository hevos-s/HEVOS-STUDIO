export const ALL_LESSONS = CURRICULUM_STAGES.flatMap((stage) => stage.lessons);

export function getStageById(stageId) {
  return CURRICULUM_STAGES.find((s) => s.id === stageId) || CURRICULUM_STAGES[0];
}

export function getLessonById(lessonId) {
  return ALL_LESSONS.find((l) => l.id === lessonId) || ALL_LESSONS[0];
}

export function getNextLesson(lessonId) {
  const idx = ALL_LESSONS.findIndex((l) => l.id === lessonId);
  if (idx < 0 || idx + 1 >= ALL_LESSONS.length) return null;
  return ALL_LESSONS[idx + 1];
}

export function getPrevLesson(lessonId) {
  const idx = ALL_LESSONS.findIndex((l) => l.id === lessonId);
  if (idx <= 0) return null;
  return ALL_LESSONS[idx - 1];
}
